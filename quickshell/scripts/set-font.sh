#!/bin/bash
# Применяет шрифт во всей системе.
# Использование: set-font.sh ui|mono "Название семейства"
#
#   ui   - шрифт интерфейса: fontconfig (sans-serif, system-ui) и GTK (font-name)
#   mono - моноширинный шрифт: fontconfig (monospace), GTK (monospace-font-name) и kitty
#
# Сам шрифт панели и бара Quickshell берёт из Settings.qml, здесь его трогать не нужно.
role=$1
family=$2
config_home="${XDG_CONFIG_HOME:-$HOME/.config}"

[ -z "$family" ] && exit 1
case $role in
    ui|mono) ;;
    *) echo "Unknown role: $role" >&2; exit 1 ;;
esac

# --- fontconfig: подхватывают Qt, GTK, Firefox и остальные после перезапуска ---
xml_escape() {
    local s=$1
    s=${s//&/&amp;}
    s=${s//</&lt;}
    s=${s//>/&gt;}
    printf '%s' "$s"
}

write_fontconfig() {
    local conf_dir="$config_home/fontconfig/conf.d"
    local file="$conf_dir/61-rice-$role.conf"
    local fam aliases=""
    fam=$(xml_escape "$family")

    case $role in
        ui)   generics="sans-serif system-ui" ;;
        mono) generics="monospace" ;;
    esac

    for g in $generics; do
        aliases+="  <alias binding=\"same\">
    <family>$g</family>
    <prefer><family>$fam</family></prefer>
  </alias>
"
    done

    mkdir -p "$conf_dir"
    cat > "$file" <<EOF
<?xml version="1.0"?>
<!DOCTYPE fontconfig SYSTEM "urn:fontconfig:fonts.dtd">
<!-- Generated by quickshell panel (set-font.sh) -->
<fontconfig>
$aliases</fontconfig>
EOF
}

# --- GTK: Nautilus и другие GTK-приложения читают шрифт из gsettings ---
set_gtk_font() {
    local key=$1 cur size
    command -v gsettings >/dev/null 2>&1 || return
    # Размер оставляем прежний, меняем только семейство
    cur=$(timeout 3 gsettings get org.gnome.desktop.interface "$key" 2>/dev/null | tr -d "'")
    size=${cur##* }
    [[ $size =~ ^[0-9]+(\.[0-9]+)?$ ]] || size=11
    timeout 3 gsettings set org.gnome.desktop.interface "$key" "$family $size" 2>/dev/null
}

# --- kitty: font_family лежит в отдельном font.conf, который подключает kitty.conf ---
set_kitty_font() {
    mkdir -p "$config_home/kitty"
    printf 'font_family      %s\n' "$family" > "$config_home/kitty/font.conf"
    # SIGUSR1 заставляет все открытые kitty перечитать конфиг
    pkill -USR1 -x kitty 2>/dev/null
    return 0
}

write_fontconfig

case $role in
    ui)   set_gtk_font font-name ;;
    mono) set_gtk_font monospace-font-name; set_kitty_font ;;
esac
